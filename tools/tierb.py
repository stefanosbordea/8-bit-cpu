"""docs/TIER_B.md: how fast can the LS CPU run a model whose weights do not fit the block RAM and live in the DDR2?

The cycle counts come from the analytic model that tools/costfit.py fits to the generated program (the generator
itself refuses models above 2^19 bytes of data memory). Everything else is arithmetic on the board facts.

    PYTHONPATH=. .venv/bin/python tools/tierb.py relu [runs/NAME/result.json ...]
"""
import json
import sys

import numpy as np

from lsllm.config import ModelConfig

sys.argv, FFN, RUNS = sys.argv[:1], sys.argv[1], sys.argv[2:]
from tools.costfit import terms                                     # noqa: E402  (reads sys.argv when imported)

CLOCK, BRAM, DDR2, PEAK = 100e6, 135 * 4096, 128 * 2 ** 20, 1.3e9
fit = json.load(open("docs/cost_fit_%s.json" % FFN))
coef = np.array(fit["coefficients"])
num = lambda v: "{:,}".format(int(round(v)))


def cycles(cfg, n):
    """Cycles of one token with n keys in the context; rows longer than 255 need `MACL` (one more instruction each)."""
    c = float(np.dot(coef, terms(cfg, n)))
    long_rows = cfg.n_layers * ((cfg.dim > 255) * (cfg.dim + 2 * cfg.kv_dim + (2 if FFN == "swiglu" else 1) * cfg.hidden_dim) + (cfg.hidden_dim > 255) * cfg.dim)
    return c + 4 * long_rows + (cfg.dim > 255) * 4 * cfg.vocab_size


def row(name, cfg, note=""):
    span = cfg.window or cfg.max_seq_len
    weights = cfg.n_params()                                                    # everything, E included, is on the tape
    in_bram = cfg.n_layers * 2 * cfg.kv_dim * span + 64 * 256 + 16384           # KV cache, tables, scratch and records
    c64, c256 = cycles(cfg, min(64, span)), cycles(cfg, min(256, span))
    return [name, cfg.n_layers, cfg.dim, cfg.hidden_dim, cfg.window or "-", num(cfg.n_params()), "%.2f" % (weights / 2 ** 20),
            num(in_bram) + (" (does not fit)" if in_bram > BRAM else ""), num(c64), "%.1f" % (CLOCK / c64), num(c256), "%.1f" % (CLOCK / c256),
            "%.1f" % (weights * CLOCK / c64 / 1e6), note]


shape = lambda L, D, F, window=0: ModelConfig(vocab_size=512, dim=D, n_layers=L, n_heads=2, n_kv_heads=1, hidden_dim=F, max_seq_len=256, ffn=FFN, window=window)
rows = []
for path in RUNS:
    r = json.load(open(path))
    rows.append(row("trained: " + path.split("/")[-2], ModelConfig(**r["config"]), "validation %.3f nats/token" % r["val_loss"]))
rows += [row("example", shape(4, 160, 480)), row("example", shape(6, 192, 510)), row("example", shape(8, 256, 510, 128), "attention window 128"),
         row("example", shape(12, 384, 510, 64), "attention window 64"),
         row("example", shape(16, 510, 510, 48), "attention window 48; the largest shape the rules allow")]
header = ["model", "L", "D", "F", "window", "parameters", "weights in DDR2 (MiB)", "bytes in block RAM (KV cache, tables, scratch)", "cycles/token @64", "tokens/s @64",
          "cycles/token @256", "tokens/s @256", "weight bytes read per second (MB/s) @64", "note"]
lines = ["# Tier B: weights in the DDR2", "",
         "Generated by `tools/tierb.py %s`. Cycle counts: the analytic model of `tools/costfit.py`, fitted to the generated LS" % FFN,
         "program on %d shapes (largest error %.2f%%, on %d shapes not used for the fit %.2f%%). The fit covers D up to 160;" % (
             fit["fit_shapes"], 100 * fit["largest_error_fit"], fit["held_out_shapes"], 100 * fit["largest_error_held_out"]),
         "larger shapes are an extrapolation of a program that is the same loop structure with longer rows (rows above 255",
         "terms take one more instruction each, included). Level L1, 100 MHz, greedy, no filter, 2 query heads, 1 KV head.", "",
         "## What limits the speed", "",
         "- The multiply-accumulate unit does one product per clock: 100 million per second. A token needs about one product per",
         "  weight, so tokens/s is about 100,000,000 / (parameters x 1.1). The overhead per row (24 to 28 cycles) matters less",
         "  as rows get longer: larger models use the stream better.",
         "- The DDR2 is not the limit. Its controller delivers up to 16 bytes per 81.25 MHz clock (1.3 GB/s peak, research/09);",
         "  one stream consumes at most 1 byte per clock (100 MB/s). The last column shows the real demand: far below both.",
         "  The condition is sequential access: the matrices are stored in the order the program reads them (a weight tape),",
         "  so a prefetch FIFO always has the next byte. A measured sequential rate for this board was not found in the search;",
         "  the 13x margin is what makes the claim safe.",
         "- Limits of the arithmetic and the program: every dot product at most 510 terms (24-bit accumulator with 8-bit operands),",
         "  so D and F at most 510; at most 16 layers with filter and sampling (64 lookup tables); the unrolled program must fit",
         "  4,096 words (about 300 words per layer with 2 heads: 12 layers; more layers need a layer loop driven by records,",
         "  like the head records); the KV cache, E, tables and scratch must fit the %s bytes of block RAM, which the" % num(BRAM),
         "  attention window makes possible for the larger shapes.",
         "- The embedding matrix E is on the tape as well: the output layer reads it in order, and the one row that the",
         "  embedding lookup needs is a single jump of the tape per token (one read latency of the controller, not measured).",
         "- 128 MiB hold any model that these limits allow (the largest shape below uses %s MiB)." % rows[-1][6], "",
         "## Speed by model size", ""]
lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
lines += ["", "What the CPU needs for this is listed in `docs/HARDWARE_CHANGES.md`, section 3."]
open("docs/TIER_B.md", "w").write("\n".join(lines) + "\n")
print("\n".join(lines[-12:]))
