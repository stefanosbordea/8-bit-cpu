#!/usr/bin/env python3
"""docs/ASKS_SOURCES.md and the row of SOURCES.md: where the program text of every request comes from, with its licence.

    PYTHONPATH=. .venv/bin/python tools/asks_sources.py data/asks/texts_C2.jsonl

The argument is the frozen text list of the board model (quick/asks_all_texts.py). One row per request of the suite:
the human-written function that is its training text (repository, file, name in that repository, licence) or the
local model that wrote it.
"""
import json
import sys
from collections import Counter

from lsllm.asks import ASKS, SOLUTIONS, load_jsonl

frozen = sys.argv[1]
asks = load_jsonl(ASKS)
solved = {row["id"]: row for row in load_jsonl(SOLUTIONS)}
texts = {row["id"]: row for row in load_jsonl(frozen)}
human = {key: row for key, row in texts.items() if not row["source"].startswith("Qwen")}
generated = {key: row for key, row in texts.items() if row["source"].startswith("Qwen")}
bundled = sum(1 for row in human.values() if "helpers" in row.get("kind", ""))
licences = Counter(row["licence"] for row in human.values())
repos = Counter(row["source"] for row in human.values())
lines = ["# Sources of the request programs", "",
         "Generated by `tools/asks_sources.py %s`. The board model is trained to write one program per request of the suite" % frozen,
         "(`data/asks/asks.jsonl`, %d requests): %d are human-written functions of the licensed corpus (renamed to the" % (len(asks), len(human)),
         "request's name, docstring and import-bound type hints removed, in %d cases with the helper functions of the same file" % bundled,
         "moved inside, re-run against the tests); %d were written by the local open model Qwen2.5-Coder-1.5B-Instruct" % len(generated),
         "(Apache-2.0, run with llama.cpp) and kept only because they pass the tests of the request; %d have no text." % (len(asks) - len(texts)),
         "No program text was written by Claude or by the authors of this project. The tests, the request lines and the phrases",
         "were written for this project by Claude agents (`LOG.md`, [asks]).", "",
         "Licences of the human-written texts: " + ", ".join("%s %d" % pair for pair in licences.most_common()) + ".", "",
         "| request | text from | file | name there | licence |", "|---|---|---|---|---|"]
for ask in asks:
    if ask["id"] in human:
        row, found = human[ask["id"]], solved.get(ask["id"], {})
        lines.append("| %s | %s | `%s` | `%s` | %s |" % (ask["name"], row["source"], row.get("path") or found.get("path", ""), row.get("original_name", ask["name"]), row["licence"]))
    elif ask["id"] in generated:
        lines.append("| %s | Qwen2.5-Coder-1.5B-Instruct, local | - | - | model Apache-2.0 |" % ask["name"])
    else:
        lines.append("| %s | no text: not trained | - | - | - |" % ask["name"])
open("docs/ASKS_SOURCES.md", "w").write("\n".join(lines) + "\n")
row = ("| Program texts of the request suite (board model) | code used as training text | per request: `docs/ASKS_SOURCES.md` | per repository: %s (rows of CodeSearchNet "
       "that said only \"BSD\" were read at the repository on 2026-11-14) | %d human-written functions from %d repositories of the licensed corpus (most from %s), each renamed "
       "to the name of its request, docstring removed, in %d cases with the helper functions of its file moved inside (`quick/asks_texts.py`, `quick/asks_bundle.py`); %d more "
       "programs written by the local Qwen2.5-Coder-1.5B model and kept only if they pass the tests of the request (`quick/qwen_asks.py`). The frozen list of the board model "
       "is `%s` |" % (", ".join("%s %d" % pair for pair in licences.most_common()), len(human), len(repos), ", ".join("%s %d" % pair for pair in repos.most_common(8)),
                      bundled, len(generated), frozen))
text = open("SOURCES.md").read().split("\n")
kept = [line for line in text if not line.startswith("| Program texts of the request suite (board model)")]
at = next(g for g, line in enumerate(kept) if line.startswith("| llama.cpp release b12361"))
kept.insert(at + 1, row)
open("SOURCES.md", "w").write("\n".join(kept))
print("\n".join(lines[2:11]))
