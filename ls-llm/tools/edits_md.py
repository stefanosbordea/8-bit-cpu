"""EDITS.md: every weight edit of every editing session (tensor, positions, old and new values), the budgeted runs,
and the held-out check before and after. Generated from edits/<session>/ (lsllm/edit/session.py) and results/results.jsonl.

    PYTHONPATH=. .venv/bin/python tools/edits_md.py edits/s1 edits/s2 ...
"""
import json
import os
import sys

from lsllm.edit.session import Session, summary

BENCHES = (("custom", "custom 200"), ("mbpp", "MBPP"), ("humaneval", "HumanEval"))
pct = lambda v: "-" if v is None else "%.1f%%" % (100 * v)


def held_out(model, edit):
    """{(benchmark, filter): metrics} of the greedy test rows of the int8 model `model` with this edit tag."""
    found = {}
    for line in open("results/results.jsonl"):
        r = json.loads(line)
        if r["model"].replace("+filter", "") == model and r["variant"] == "int8" and r.get("edit", "") == edit and r["split"] == "test" \
                and r["decoding"]["temperature"] == 0:
            found[r["benchmark"], r["filter"] or "off"] = r["metrics"]
    return found


def main(sessions):
    lines = ["# EDITS: weight-space editing of the int8 model without gradients", "",
             "Generated by `tools/edits_md.py`. Rules of a session (enforced by `lsllm/edit/session.py`): no gradients and no",
             "training; the model is run on data only through the two budgeted calls (`evaluate`, `trace`), at most 50 per session;",
             "the data of those calls is practice data only (the 200 custom practice tasks and windows of the training text);",
             "every edit must keep the hardware rules (int8, weights in -127..127, table and preload ranges, no stream that could",
             "leave the 24-bit accumulator) and is logged with tensor, positions, old and new values. The complete lists are in",
             "`edits/<session>/edits.jsonl`; the scripts and notes of each session are in `edits/<session>/scripts/` and `NOTES.md`.", ""]
    base = os.path.basename(os.path.abspath(Session(sessions[0]).budget["base"]))
    rows = [("before editing", held_out(base, ""))] + [("session " + os.path.basename(s), held_out(base, "session " + os.path.basename(s))) for s in sessions]
    lines += ["## Held-out check: test sets before and after (greedy; measured after the sessions ended, never seen by them)", ""]
    header = ["model", "syntax filter"]
    for _, name in BENCHES:
        header += [name + " pass@1", name + " syntax ok", name + " runs ok"]
    lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for label, found in rows:
        for flt in ("off", "on"):
            cells = []
            for bench, _ in BENCHES:
                m = found.get((bench, flt))
                cells += [pct(m["pass@1"]), pct(m["syntax_ok"]), pct(m["runs_ok"])] if m else ["-", "-", "-"]
            if any(c != "-" for c in cells):
                lines.append("| " + " | ".join([label, flt] + cells) + " |")
    lines += ["", "## Practice scores of each session: first and best budgeted evaluation", "",
              "| session | strategy | runs used | edits in the log | practice pass@1 first -> kept | syntax ok | runs ok | tests passed | practice loss |", "|---|---|---|---|---|---|---|---|---|"]
    for s in sessions:
        session = Session(s)
        evals = [run["result"] for run in session.budget["runs"] if run.get("result")]
        if not evals:
            continue
        first, last = evals[0], evals[-1]
        show = lambda key, form="%.3f": (form + " -> " + form) % (first[key], last[key])
        lines.append("| %s | %s | %d | %d | %s | %s | %s | %s | %s |" % (
            os.path.basename(s), session.budget["strategy"].replace("|", "/"), len(session.budget["runs"]), len(session.edits()),
            show("pass@1"), show("syntax_ok"), show("runs_ok"), show("tests_passed", "%.4f"), show("practice_loss", "%.4f")))
    lines.append("")
    lines.append("\"kept\" is the last budgeted evaluation of the session, which is the model left in its folder.")
    lines.append("")
    for s in sessions:
        lines += summary(s) + [""]
    open("EDITS.md", "w").write("\n".join(lines) + "\n")
    print("wrote EDITS.md: %d lines, %d sessions" % (len(lines), len(sessions)))


if __name__ == "__main__":
    main(sys.argv[1:])
